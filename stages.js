export function phasesFor(round){
  const phases=stages[round.step-1].phases;
  if(round.step===10)return [{mode:'open',questions:[lenses[round.lens].see]}];
  if(round.step===11 && round.context)return [{mode:'open',questions:[round.context,...phases[0].questions.slice(1)]}];
  return phases;
}
